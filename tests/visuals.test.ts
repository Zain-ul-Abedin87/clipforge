import { after, describe, test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "clipforge-visuals-"));
process.env.LLM_SETTINGS_FILE = path.join(tmp, "llm_settings.json");
process.env.LLM_USAGE_FILE = path.join(tmp, "llm_usage.json");
process.env.FEATURE_SETTINGS_FILE = path.join(tmp, "features.json");
delete process.env.PEXELS_API_KEY;
delete process.env.PIXABAY_API_KEY;
process.env.IMAGEGEN_DIR = path.join(tmp, "imagegen");
after(() => fs.rmSync(tmp, { recursive: true, force: true }));

const S = await import("../src/lib/agents/llm/settings.js");
const F = await import("../src/lib/settings/features.js");
const { assignUnique, runVisualPlan, tierOf } = await import("../src/lib/assets/visualPlan.js");
const { dedupeQueries, ruleMap } = await import("../src/lib/assets/prompt-mapper.js");
const { buildWorkflow, generateImage, modelLicense, setComfyFetch } = await import("../src/lib/assets/imagegen.js");
const { classifyLicense, ledgerCategory } = await import("../src/lib/assets/licenseLedger.js");
const { readLicenseSidecar } = await import("../src/lib/assets/stock/license.js");
const { pexelsLicense } = await import("../src/lib/assets/stock/pexels.js");

S.saveLlmSettings({ primary: "off" });

const cand = (key: string, tier: 0 | 1 | 2 | 3, score = 1) => ({ key, tier, score, source: "x", license: "l", kind: "video" as const });

describe("ranking + unique assignment", () => {
  test("product footage > product photo > stock > generated; most constrained segment chooses first", () => {
    const cands = new Map([
      [1, [cand("stockA", 2, 5), cand("own1", 0, 1)]],
      [2, [cand("own1", 0, 3)]], // only one option: it must get own1
      [3, [cand("stockA", 2), cand("stockB", 2, 2)]],
    ]);
    const { picks, forcedReuse } = assignUnique([1, 2, 3].map((id) => ({ id, allowGenerated: true })), cands);
    assert.deepEqual(picks.map((p) => p.cand?.key), ["stockA", "own1", "stockB"]);
    assert.equal(forcedReuse, 0);
  });

  test("nothing unused: generated when allowed, else a counted forced reuse of the least-used option", () => {
    const cands = new Map([[1, [cand("a", 0)]], [2, [cand("a", 0)]], [3, [cand("a", 0)]]]);
    const r = assignUnique([{ id: 1, allowGenerated: false }, { id: 2, allowGenerated: true }, { id: 3, allowGenerated: false }], cands);
    assert.equal(r.picks[1].generate, true);
    assert.equal(r.picks[2].forced, true);
    assert.equal(r.forcedReuse, 1);
  });

  test("tiers of existing assets: product video 0, product photo 1, stock 2, cards none", () => {
    assert.equal(tierOf({ source: "youtube_exact_model", kind: "video" }, true), 0);
    assert.equal(tierOf({ source: "presskit", kind: "image" }, true), 1);
    assert.equal(tierOf({ source: "pexels", kind: "video" }, false), 2);
    assert.equal(tierOf({ source: "graphic", kind: "image" }, false), null);
  });
});

describe("prompt mapper (rules) and licences", () => {
  test("rule queries; product segments are never generated; repeated queries are made distinct", () => {
    const a = ruleMap({ id: 1, text: "A quiet campfire burning in the forest at night." });
    assert.ok(a.query.includes("campfire") && a.allowGenerated);
    assert.equal(ruleMap({ id: 2, text: "It costs 499 dollars.", product: "Sig P365" }).allowGenerated, false);
    const d = dedupeQueries([{ ...a, id: 1 }, { ...a, id: 2 }], [{ id: 1, text: a.query }, { id: 2, text: "campfire smoke rising slowly" }]);
    assert.notEqual(d[0].query, d[1].query);
  });

  test("licence metadata: stock sidecar fields, generated pictures are 'generated' in the ledger", () => {
    const m = pexelsLicense({ source: "pexels", id: "pexels_1_1920", kind: "video", location: "", pageUrl: "https://pexels.com/v/1", license: "Pexels License", width: 1920, height: 1080, score: 1, author: "Ann" }, "campfire");
    assert.equal(m.licenseUrl, "https://www.pexels.com/license/");
    assert.equal(m.author, "Ann");
    assert.equal(ledgerCategory("imagegen"), "generated");
    assert.equal(classifyLicense("Generated by ClipForge (local sdxl_turbo, x)", "imagegen"), "generated");
    assert.match(modelLicense("flux1-schnell-Q4_K_S.gguf"), /Apache/);
  });
});

describe("ComfyUI image generation (fake server)", () => {
  test("workflow per checkpoint type; result saved with a licence sidecar; cached by prompt", async () => {
    assert.equal((buildWorkflow("p", "sd_xl_turbo_1.0_fp16.safetensors", 1)["1"] as { class_type: string }).class_type, "CheckpointLoaderSimple");
    assert.equal((buildWorkflow("p", "flux1-schnell-Q4.gguf", 1)["1"] as { class_type: string }).class_type, "UnetLoaderGGUF");
    let posts = 0;
    setComfyFetch((async (url: string) => {
      const u = String(url);
      if (u.endsWith("/prompt")) return (posts++, new Response(JSON.stringify({ prompt_id: "p1" })));
      if (u.includes("/history/")) return new Response(JSON.stringify({ p1: { outputs: { "7": { images: [{ filename: "a.png", subfolder: "", type: "output" }] } } } }));
      if (u.includes("/view")) return new Response(new Uint8Array([137, 80, 78, 71]));
      return new Response("", { status: 404 });
    }) as unknown as typeof fetch);
    const out = path.join(tmp, "gen");
    const g = await generateImage("a campfire at night", { url: "http://comfy", ckpt: "sd_xl_turbo_1.0_fp16.safetensors", outDir: out, pollMs: 1 });
    assert.ok(fs.existsSync(g.file));
    assert.match(readLicenseSidecar(g.file)!.license, /Generated by ClipForge/);
    await generateImage("a campfire at night", { url: "http://comfy", ckpt: "sd_xl_turbo_1.0_fp16.safetensors", outDir: out, pollMs: 1 });
    assert.equal(posts, 1, "second call is served from the cache");
  });
});

describe("runVisualPlan on a project", () => {
  test("every segment gets a unique visual; generated pictures fill only non-product gaps; all licences logged", async () => {
    const dir = path.join(tmp, "proj");
    fs.mkdirSync(dir, { recursive: true });
    const own = path.join(dir, "p365.mp4");
    fs.writeFileSync(own, "x");
    fs.writeFileSync(path.join(dir, "scenes.json"), JSON.stringify([
      { id: 1, start: 0, end: 4, text: "Campfire smoke drifts over the camp at dusk.", type: "broll", queries: [], section: 0, labeledBy: "heuristic" },
      { id: 2, start: 4, end: 8, text: "The Sig P365 carries ten rounds.", type: "product", product_name: "Sig P365", queries: [], section: 1, labeledBy: "heuristic" },
      { id: 3, start: 8, end: 12, text: "A backpack full of gear waits by the tent.", type: "broll", queries: [], section: 0, labeledBy: "heuristic" },
      { id: 4, start: 12, end: 14, text: "Number one", type: "graphic", queries: [], section: 1, labeledBy: "heuristic" },
    ]));
    fs.writeFileSync(path.join(dir, "assets.json"), JSON.stringify({ "2": { path: own, source: "youtube_exact_model", license: "Exact-model review clip", url: "https://yt/1", kind: "video" }, "1": { path: "card.png", source: "graphic", license: "Generated by ClipForge", url: "", kind: "image" } }));
    F.saveFeatures({ stock: { imagegen: true, comfyUrl: "http://comfy" } });
    const logs: string[] = [];
    const plan = await runVisualPlan(dir, { apply: true, log: (m) => logs.push(m) });
    assert.equal(plan.summary.segments, 3);
    assert.equal(plan.summary.unique, 3, JSON.stringify(plan.segments));
    assert.equal(plan.summary.forcedReuse, 0);
    assert.equal(plan.summary.withLicense, 3);
    const byId = new Map(plan.segments.map((s) => [s.id, s]));
    assert.equal(byId.get(2)!.tierLabel, "product footage");
    assert.equal(byId.get(1)!.tierLabel, "generated");
    assert.ok(logs.some((l) => /#2 product footage: youtube_exact_model \| Exact-model review clip/.test(l)));
    const assets = JSON.parse(fs.readFileSync(path.join(dir, "assets.json"), "utf8"));
    assert.equal(assets["1"].source, "imagegen", "the fallback card on a footage scene was replaced");
    assert.equal(assets["2"].path, own, "real product footage is never replaced");
    assert.ok(fs.existsSync(path.join(dir, "licenses.json")));
  });
});
