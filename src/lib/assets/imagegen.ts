import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { paths } from "../paths.js";
import { LicenseMeta, writeLicenseSidecar } from "./stock/license.js";

/**
 * Optional local image generation through ComfyUI (http://127.0.0.1:8188, off by default:
 * features.json stock.imagegen). Last tier: only for non-product segments that no real picture
 * fits. One picture at a time; ComfyUI frees its VRAM between runs (the LLM is unloaded first by the
 * model loader when the visuals step ends its text work).
 *
 * Checkpoints:
 *  - SDXL-Turbo (`*.safetensors`, 1-4 steps, cfg 1): Stability AI Community License (free under
 *    $1M yearly revenue; check the current terms).
 *  - Flux.1 schnell GGUF (`*.gguf`, needs the ComfyUI-GGUF custom nodes, 4 steps): Apache-2.0.
 */

export let comfyFetch: typeof fetch = (...a) => fetch(...a);
export const setComfyFetch = (f: typeof fetch) => (comfyFetch = f);

export const isFlux = (ckpt: string) => /flux/i.test(ckpt) || /\.gguf$/i.test(ckpt);
export const modelLicense = (ckpt: string) => (isFlux(ckpt) ? "Apache-2.0 (FLUX.1 schnell)" : "Stability AI Community License (SDXL-Turbo)");

/** ComfyUI API workflow (the JSON "Save (API format)" writes) for one 16:9 picture. */
export function buildWorkflow(prompt: string, ckpt: string, seed: number, w = 1344, h = 768): Record<string, unknown> {
  const negative = "text, watermark, logo, letters, blurry, deformed, low quality, person face";
  if (isFlux(ckpt)) {
    return {
      "1": { class_type: "UnetLoaderGGUF", inputs: { unet_name: ckpt } },
      "2": { class_type: "DualCLIPLoader", inputs: { clip_name1: "t5xxl_fp8_e4m3fn.safetensors", clip_name2: "clip_l.safetensors", type: "flux" } },
      "3": { class_type: "VAELoader", inputs: { vae_name: "ae.safetensors" } },
      "4": { class_type: "CLIPTextEncode", inputs: { text: prompt, clip: ["2", 0] } },
      "5": { class_type: "CLIPTextEncode", inputs: { text: "", clip: ["2", 0] } },
      "6": { class_type: "EmptyLatentImage", inputs: { width: w, height: h, batch_size: 1 } },
      "7": { class_type: "KSampler", inputs: { model: ["1", 0], positive: ["4", 0], negative: ["5", 0], latent_image: ["6", 0], seed, steps: 4, cfg: 1, sampler_name: "euler", scheduler: "simple", denoise: 1 } },
      "8": { class_type: "VAEDecode", inputs: { samples: ["7", 0], vae: ["3", 0] } },
      "9": { class_type: "SaveImage", inputs: { images: ["8", 0], filename_prefix: "clipforge" } },
    };
  }
  return {
    "1": { class_type: "CheckpointLoaderSimple", inputs: { ckpt_name: ckpt } },
    "2": { class_type: "CLIPTextEncode", inputs: { text: prompt, clip: ["1", 1] } },
    "3": { class_type: "CLIPTextEncode", inputs: { text: negative, clip: ["1", 1] } },
    "4": { class_type: "EmptyLatentImage", inputs: { width: w, height: h, batch_size: 1 } },
    "5": { class_type: "KSampler", inputs: { model: ["1", 0], positive: ["2", 0], negative: ["3", 0], latent_image: ["4", 0], seed, steps: 4, cfg: 1, sampler_name: "euler_ancestral", scheduler: "normal", denoise: 1 } },
    "6": { class_type: "VAEDecode", inputs: { samples: ["5", 0], vae: ["1", 2] } },
    "7": { class_type: "SaveImage", inputs: { images: ["6", 0], filename_prefix: "clipforge" } },
  };
}

export interface GenResult {
  file: string;
  license: LicenseMeta;
  ms: number;
}

const sleep = (ms: number) => new Promise<void>((r) => setTimeout(r, ms));

/** Generates one picture; cached by prompt + checkpoint in cache/imagegen. */
export async function generateImage(prompt: string, o: { url: string; ckpt: string; outDir?: string; timeoutMs?: number; pollMs?: number; log?: (m: string) => void }): Promise<GenResult> {
  const key = crypto.createHash("sha1").update(`${o.ckpt}|${prompt}`).digest("hex").slice(0, 16);
  const outDir = o.outDir ?? (process.env.IMAGEGEN_DIR || path.join(paths.root, "cache", "imagegen"));
  fs.mkdirSync(outDir, { recursive: true });
  const file = path.join(outDir, `${key}.png`);
  const license: LicenseMeta = { source: "imagegen", id: key, pageUrl: "", license: `Generated by ClipForge (local ${path.basename(o.ckpt)}, ${modelLicense(o.ckpt)})`, attributionRequired: false, fetchedAt: new Date().toISOString(), model: o.ckpt, prompt };
  if (fs.existsSync(file)) return { file, license, ms: 0 };
  const t0 = Date.now();
  const base = o.url.replace(/\/+$/, "");
  const seed = parseInt(key.slice(0, 8), 16);
  const res = await comfyFetch(`${base}/prompt`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ prompt: buildWorkflow(prompt, o.ckpt, seed), client_id: "clipforge" }) });
  if (!res.ok) throw new Error(`ComfyUI ${res.status}: ${(await res.text()).slice(0, 200)} (is ComfyUI running at ${base}, and is ${o.ckpt} in its models folder?)`);
  const { prompt_id } = (await res.json()) as { prompt_id: string };
  const until = Date.now() + (o.timeoutMs ?? 180_000);
  while (Date.now() < until) {
    await sleep(o.pollMs ?? 1000);
    const h = (await (await comfyFetch(`${base}/history/${prompt_id}`)).json()) as Record<string, { outputs?: Record<string, { images?: { filename: string; subfolder: string; type: string }[] }> }>;
    const img = Object.values(h[prompt_id]?.outputs ?? {}).flatMap((x) => x.images ?? [])[0];
    if (!img) continue;
    const view = await comfyFetch(`${base}/view?filename=${encodeURIComponent(img.filename)}&subfolder=${encodeURIComponent(img.subfolder)}&type=${encodeURIComponent(img.type)}`);
    fs.writeFileSync(file, Buffer.from(await view.arrayBuffer()));
    writeLicenseSidecar(file, license);
    const ms = Date.now() - t0;
    o.log?.(`[imagegen] ${path.basename(o.ckpt)}: "${prompt.slice(0, 60)}" in ${(ms / 1000).toFixed(1)} s`);
    return { file, license, ms };
  }
  throw new Error(`ComfyUI did not finish within ${Math.round((o.timeoutMs ?? 180_000) / 1000)} s`);
}
