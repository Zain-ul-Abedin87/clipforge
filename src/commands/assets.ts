/** Runs async jobs with a fixed concurrency. */
async function pool<T>(items: T[], n: number, fn: (item: T, i: number) => Promise<void>): Promise<void> {
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(n, items.length) }, async () => {
      while (next < items.length) {
        const i = next++;
        await fn(items[i], i);
      }
    }),
  );
}

const csv = (v: unknown) => {
  const s = String(v ?? "");
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export async function assets(opts: AssetsOpts, log: (m: string) => void = console.log): Promise<number> {
  const dir = projectDir(opts.project);
  const scenesFile = path.join(dir, "scenes.json");
  if (!fs.existsSync(scenesFile)) {
    log(`[assets] ${scenesFile} missing. Run \`clipforge plan\` first.`);
    return 1;
  }
  const project = readJson<{ channel?: string; niche?: string }>(path.join(dir, "project.json"));
  const channel = project.channel ?? "default";
  const chDir = path.join(paths.channels, channel);
  const style = loadStyle(channel);
  const niche = loadNiche(projectNicheName(project, style));
  const colors = (style.colors ?? {}) as Record<string, string>;
  const fonts = (style.fonts ?? {}) as Record<string, string>;
  const cardStyle: CardStyle = {
    primary: colors.primary ?? "#E8A317",
    secondary: colors.secondary ?? "#1C1C1C",
    text: colors.text ?? "#FFFFFF",
    accent: colors.accent ?? "#C0392B",
    titleFont: fonts.title,
    bodyFont: fonts.body,
  };

  const inputs = {
    scenes: fingerprint(scenesFile),
    style: fingerprint(path.join(chDir, "style.json")),
    pexels: String(hasKey("PEXELS_API_KEY")),
    pixabay: String(hasKey("PIXABAY_API_KEY")),
    unsplash: String(hasKey("UNSPLASH_ACCESS_KEY")),
    providers: nicheProviders(niche).join(","),
    footage: footageSignature(chDir),
    ranker: fs.existsSync(path.join(paths.python, "clip_score.py")) ? "clip-v7" : "stock-rank-v7",
    niche: `${niche.name}:${fingerprint(path.join(nichesDir, `${niche.name}.json`))}`,
    agent: agentEnabled() ? `agent-v1:${agentModel()}` : "off",
  };
  if (!opts.force && isCached(dir, "assets", inputs, ["assets.json", "license_log.csv"])) {
    log(`[assets] cached -> ${path.join(dir, "assets.json")} (use --force to redo)`);
    return 0;
  }

  const scenes = readJson<Scene[]>(scenesFile);
  const graphicsDir = path.join(dir, "graphics");

  // Official product photos from the manufacturer's site, for products that have no media yet.
  if (niche.product.sources.includes("official")) {
    const names = [...new Set(scenes.map((s) => s.product_name).filter((n): n is string => !!n))];
    await importOfficial(channel, names, niche, log).catch((err) => log(`[official] skipped: ${String(err)}`));
  }

  log(`[assets] indexing footage for channel "${channel}" ...`);
  const local = await indexFolder(path.join(chDir, "footage"), "local");
  const presskit = await indexFolder(path.join(chDir, "presskit"), "presskit");
  log(`[assets] video type: ${niche.label}`);
  log(`[assets] local footage: ${local.length} files, press kit: ${presskit.length} files`);
  const providers = nicheProviders(niche);
  const keyFor: Partial<Record<StockProvider, string>> = { pixabay: "PIXABAY_API_KEY", pexels: "PEXELS_API_KEY", unsplash: "UNSPLASH_ACCESS_KEY" };
  log(`[assets] stock order: ${providers.map((p) => (keyFor[p] && !hasKey(keyFor[p]!) ? `${p} (no key)` : p)).join(" -> ")}`);

  const result: Assets = {};
  const useCount = new Map<string, number>();
  const disabled = new Set<string>();
  const searchCache = new Map<string, Candidate[]>();
  const pendingDownloads: { sceneId: number; cand: Candidate }[] = [];

  const search = async (provider: StockProvider, q: string): Promise<Candidate[]> => {
    if (disabled.has(provider)) return [];
    const key = `${provider}:${q}`;
    if (searchCache.has(key)) return searchCache.get(key)!;
    try {
      // searchProvider applies the niche's blocked-terms filter (no toys/airsoft/war clips...).
      const found = await searchProvider(provider, q, niche);
      searchCache.set(key, found);
      return found;
    } catch (err) {
      if (err instanceof RateLimited || err instanceof ProviderRateLimited) {
        disabled.add(provider);
        log(`[assets] ${err.message}; skipping ${provider} for the rest of this run`);
      } else log(`[assets] ${provider} search "${q}" failed: ${String(err)}`);
      return [];
    }
  };

  /** Least-used candidate wins among the best few, so the video does not repeat the same clip. */
  const pick = (cands: Candidate[]): Candidate | null => {
    if (!cands.length) return null;
    const top = cands.slice(0, 8);
    return [...top].sort((a, b) => (useCount.get(a.id) ?? 0) - (useCount.get(b.id) ?? 0) || b.score - a.score)[0];
  };

  const fromCandidate = (scene: Scene, c: Candidate, query: string, note?: string): Asset => {
    const n = useCount.get(c.id) ?? 0;
    useCount.set(c.id, n + 1);
    const len = scene.end - scene.start;
    // Reused clips start at a different point each time; first use skips the first half second.
    const room = c.duration ? Math.max(0, c.duration - len - 0.5) : 0;
    const inPoint = c.kind === "video" && room > 0 ? Math.round((((0.5 + n * len) % room) + Number.EPSILON) * 100) / 100 : 0;
    return {
      path: c.location,
      source: c.source,
      license: c.license,
      url: c.pageUrl,
      kind: c.kind,
      author: c.author,
      width: c.width,
      height: c.height,
      duration: c.duration,
      in: inPoint,
      query,
      ...(note ? { note } : {}),
    };
  };

  const stockPools: StockPool[] = [];
  const wikiCache = new Map<string, Candidate[]>();
  const unsplashCache = new Map<string, Candidate[]>();
  const candidateFile: CandidateFile = {};
  const genericIds = new Set<number>();
  const sectionText = (secId: number) => scenes.filter((x) => x.section === secId).map((x) => x.text).join(" ");
  const categoryHints = nicheHints(niche).slice(0, niche.stock.sectionHintCount ?? 0);

  // AI Footage Agent: Claude writes the searches (exact -> broad) and the ideal-shot sentence.
  const sectionsFile = path.join(dir, "sections.json");
  const sections = fs.existsSync(sectionsFile) ? readJson<Section[]>(sectionsFile) : [];
  const sectionLabel = (s: Scene) => {
    const sec = sections[s.section];
    if (!sec) return "body";
    return sec.kind === "item" ? `product review: ${sec.product_name ?? "item"}` : sec.kind;
  };
  const agentPlan: Map<number, ScenePlan> | null = await planFootage(scenes, sectionLabel, niche, path.join(dir, "agent_footage.json"), log).catch((err) => {
    log(`[agent] failed, using rule-based searches: ${String(err)}`);
    return null;
  });

  const breakerIds = new Set<number>();
  for (const sceneOrig of scenes) {
    let scene = sceneOrig;
    const id = String(scene.id);
    const plan = agentPlan?.get(scene.id);
    if (plan && scene.type !== "graphic" && scene.type !== "product") scene = { ...scene, queries: plan.queries };
    const productTokens = scene.product_name ? tokens(scene.product_name) : [];
    // Previous scene a still (photo or card)? Then this scene must move: two stills in a row read as
    // a slideshow. Scenes waiting for a stock pick have no result yet and will be video.
    const prev = scene.id > 0 ? result[String(scene.id - 1)] : undefined;
    const mustMove = prev?.kind === "image" && niche.product.genericFallback !== false;

    if (scene.type === "graphic" && scene.graphic) {
      const file = await renderGraphic(scene.graphic, cardStyle, graphicsDir);
      result[id] = { path: file, source: "graphic", license: GENERATED, url: "", kind: "image", width: 1920, height: 1080, query: scene.graphic.kind };
      continue;
    }

    if (scene.type === "product" && !niche.product.allowStock) {
      if (scene.product_name) {
        const name = scene.product_name;
        if (niche.product.sources.includes("wikimedia") && !wikiCache.has(name)) {
          wikiCache.set(name, await searchWikimedia(name, niche.stock.blockedTerms).catch((err) => (log(`[assets] Wikimedia "${name}" failed: ${String(err)}`), [])));
        }
        candidateFile[id] = [
          ...matchLocal(local, "local", [], productTokens),
          ...matchLocal(presskit, "presskit", [], productTokens),
          ...(wikiCache.get(name) ?? []),
        ].map((c) => ({ ...c, query: name }));
      }
      // Own footage / press kit only: stock footage of "a gun" would show the wrong model in a review.
      const movingOnly = (list: Candidate[]) => (mustMove ? list.filter((x) => x.kind === "video") : list);
      const c =
        pick(movingOnly(matchLocal(local, "local", [], productTokens))) ??
        pick(movingOnly(matchLocal(presskit, "presskit", [], productTokens)));
      if (c) {
        result[id] = fromCandidate(scene, c, scene.product_name!);
        continue;
      }
      if (mustMove) {
        // Product photos exist but the scene before was a still: moving footage of the same type of gun
        // here, the photos come back on the next product scene.
        const context = `${scene.product_name ?? ""} ${scene.text} ${sectionText(scene.section)}`;
        const cat = categoryHints.find(([re]) => re.test(context))?.[1] ?? niche.stock.fallbackQuery;
        scene = { ...scene, queries: plan ? plan.queries.slice(1) : [cat, `${cat} close up`, niche.stock.fallbackQuery] };
        breakerIds.add(scene.id);
      }
    }
    if (scene.type === "product" && !niche.product.allowStock && !breakerIds.has(scene.id)) {
      // Unsplash photos whose description names the exact model, as another product option.
      if (niche.product.sources.includes("unsplash") && scene.product_name && hasKey("UNSPLASH_ACCESS_KEY")) {
        const name = scene.product_name;
        if (!unsplashCache.has(name)) {
          const found = await searchProvider("unsplash", name, niche).catch(() => []);
          unsplashCache.set(name, found.filter((c) => productTokens.every((t) => tokens(c.tags ?? "").includes(t))));
        }
        candidateFile[id] = [...(candidateFile[id] ?? []), ...unsplashCache.get(name)!.map((c) => ({ ...c, query: name }))];
      }
      // Tier 3 for products: free-licensed photos of the exact model on Wikimedia Commons.
      if (niche.product.sources.includes("wikimedia") && scene.product_name) {
        const name = scene.product_name;
        if (!wikiCache.has(name)) {
          wikiCache.set(name, await searchWikimedia(name, niche.stock.blockedTerms).catch((err) => (log(`[assets] Wikimedia "${name}" failed: ${String(err)}`), [])));
        }
        const w = pick(wikiCache.get(name)!);
        if (w) {
          try {
            const file = await downloadWikimedia(w);
            result[id] = { ...fromCandidate(scene, w, name), path: file };
            continue;
          } catch (err) {
            log(`[assets] ${String(err)}`);
          }
        }
      }
      const u = scene.product_name ? pick(unsplashCache.get(scene.product_name) ?? []) : null;
      if (u) {
        try {
          result[id] = { ...fromCandidate(scene, u, scene.product_name!), path: await downloadCandidate(u) };
          continue;
        } catch (err) {
          log(`[assets] ${String(err)}`);
        }
      }
      if (niche.product.genericFallback === false) {
        const file = await renderTextCard("Product", scene.product_name ?? "", cardStyle, graphicsDir);
        result[id] = {
          path: file, source: "graphic", license: GENERATED, url: "", kind: "image", width: 1920, height: 1080,
          query: scene.product_name, note: "No footage or press-kit image for this product yet",
        };
        continue;
      }
      // No media of this exact model: show moving footage of the same kind of gun (the lower third
      // names the product). A name card on a black background reads as a slideshow.
      const context = `${scene.product_name ?? ""} ${scene.text} ${sectionText(scene.section)}`;
      const cat = categoryHints.find(([re]) => re.test(context))?.[1] ?? niche.stock.fallbackQuery;
      scene = { ...scene, queries: plan ? plan.queries : [cat, `${cat} close up`, niche.stock.fallbackQuery] };
      genericIds.add(scene.id);
    }

    // stock / image scenes: own footage by keywords first (tier 1), else a stock pool for CLIP ranking.
    // Own B-roll matches the scene's main visual phrase only: later queries are fallbacks (e.g. the
    // niche default "outdoor shooting range") and would put one clip on every scene.
    const wantTokens = [...new Set(tokens(scene.queries[0] ?? ""))];
    const need = Math.max(2, Math.ceil(wantTokens.length * 0.6));
    const localHit = pick(matchLocal(local, "local", wantTokens, productTokens).filter((c) => c.score >= need));
    if (localHit) {
      result[id] = fromCandidate(scene, localHit, scene.queries[0]);
      continue;
    }
    const cands: Candidate[] = [];
    const queryOf = new Map<string, string>();
    for (const q of scene.queries.slice(0, 3)) {
      for (const provider of providers) {
        for (const c of (await search(provider, q)).slice(0, 6)) {
          if (queryOf.has(c.id)) continue;
          queryOf.set(c.id, q);
          cands.push(c);
        }
      }
    }
    if (!cands.length) {
      const file = await renderTextCard("", scene.queries[0] ?? scene.text.split(/\s+/).slice(0, 6).join(" "), cardStyle, graphicsDir);
      result[id] = {
        path: file, source: "graphic", license: GENERATED, url: "", kind: "image", width: 1920, height: 1080,
        query: scene.queries[0], note: hasKey("PEXELS_API_KEY") || hasKey("PIXABAY_API_KEY") ? "No stock result" : "No stock key in .env",
      };
      continue;
    }
    stockPools.push({ scene, cands: cands.slice(0, 18), queryOf, visual: plan?.visual });
  }

  // CLIP ranking: look at each candidate's thumbnail and score it against the scene, then pick the
  // best match in scene order, with a small penalty for clips already used (variety).
  const clipScores = await rankWithClip(stockPools, log);
  const MIN_MATCH = 0.215;
  const JUNK = 0.19;
  const bestOf = (p: StockPool) => Math.max(-1, ...p.cands.map((c) => clipScores?.get(`${p.scene.id}|${c.id}`) ?? -1));
  if (clipScores && agentPlan) {
    const weak = stockPools.filter((p) => bestOf(p) < MIN_MATCH);
    const more = await broadenFootage(
      weak.map((p) => ({
        id: p.scene.id,
        text: p.scene.text,
        ...(p.scene.product_name ? { product: p.scene.product_name } : {}),
        tried: [...new Set([...p.queryOf.values(), ...p.scene.queries])],
        found: p.cands.slice(0, 6).map((c) => c.tags ?? "").filter(Boolean),
      })),
      niche,
      log,
    );
    const extra: StockPool[] = [];
    for (const p of weak) {
      const nq = more.get(p.scene.id);
      if (!nq) continue;
      const fresh: Candidate[] = [];
      for (const q of nq.queries.slice(0, 3)) {
        for (const provider of providers) {
          for (const c of (await search(provider, q)).slice(0, 6)) {
            if (p.queryOf.has(c.id)) continue;
            p.queryOf.set(c.id, q);
            fresh.push(c);
          }
        }
      }
      if (fresh.length) extra.push({ scene: p.scene, cands: fresh.slice(0, 18), queryOf: p.queryOf, visual: p.visual });
    }
    const extraScores = await rankWithClip(extra, log);
    let improved = 0;
    for (const e of extra) {
      const p = stockPools.find((x) => x.scene.id === e.scene.id)!;
      const before = bestOf(p);
      p.cands.push(...e.cands);
      for (const c of e.cands) {
        const v = extraScores?.get(`${e.scene.id}|${c.id}`);
        if (v !== undefined) clipScores.set(`${e.scene.id}|${c.id}`, v);
      }
      if (bestOf(p) > before + 0.005) improved++;
    }
    if (weak.length) log(`[agent] broaden round: ${weak.length} weak scene(s), ${improved} got a better clip`);
  }
  for (const p of stockPools) {
    candidateFile[String(p.scene.id)] = p.cands
      .map((c) => ({ ...c, match: clipScores?.get(`${p.scene.id}|${c.id}`), query: p.queryOf.get(c.id) }))
      .sort((a, b) => (b.match ?? 0) - (a.match ?? 0));
  }
  for (const p of stockPools) {
    let best: Candidate | null = null;
    let bestScore = -Infinity;
    let bestClip: number | undefined;
    p.cands.forEach((c, i) => {
      const clip = clipScores?.get(`${p.scene.id}|${c.id}`);
      // Without CLIP, fall back to the stock site's own ranking.
      const base = clip ?? c.score / 10 - i * 0.001;
      // Stills make a video feel like a slideshow (YouTube "reused content" risk): prefer motion.
      const stillPenalty = c.kind === "image" ? 0.03 : 0;
      const s = base - stillPenalty - 0.03 * (useCount.get(c.id) ?? 0);
      if (s > bestScore) [best, bestScore, bestClip] = [c, s, clip];
    });
    const c = best!;
    const asset = fromCandidate(p.scene, c, p.queryOf.get(c.id) ?? p.scene.queries[0]);
    if (bestClip !== undefined) asset.match = bestClip;
    if (genericIds.has(p.scene.id)) asset.note = "Generic footage of this type of gun (no media of this exact model yet - add some in My clips / Press kit)";
    if (breakerIds.has(p.scene.id)) asset.note = "Moving footage between product photos (two stills in a row look like a slideshow)";
    result[String(p.scene.id)] = asset;
    pendingDownloads.push({ sceneId: p.scene.id, cand: c });
  }
  // Editor trick for weak matches: instead of an unrelated clip (or a text card when nothing was
  // found), reuse the best-matching clip from a nearby scene at a different point in that clip.
  let reused = 0;
  if (clipScores) {
    for (const s of scenes) {
      if (s.type === "graphic") continue;
      const a = result[String(s.id)];
      const weak = a.source === "graphic" ? a.note?.startsWith("No stock") : a.match !== undefined && a.match < MIN_MATCH;
      if (!weak) continue;
      const donors = (within: number) =>
        scenes
          .filter((n) => n.id !== s.id && Math.abs(n.id - s.id) <= within && n.section === s.section)
          .map((n) => result[String(n.id)])
          .filter((d) => d && d.kind === "video" && (d.match ?? 0) >= 0.22 && Object.values(result).filter((x) => x.path === d.path).length < 3)
          .sort((x, y) => (y.match ?? 0) - (x.match ?? 0))[0];
      // Junk (clearly unrelated, e.g. food in a gun video): any good clip from the same section will do.
      const isJunk = a.source === "graphic" || (a.match ?? 1) < JUNK;
      const donor = donors(3) ?? (isJunk ? donors(1000) : undefined);
      if (!donor) continue;
      const len = s.end - s.start;
      const room = Math.max(0, (donor.duration ?? 0) - len - 0.5);
      const inPoint = room > 0 ? Math.round((((donor.in ?? 0) + len + 1) % room) * 100) / 100 : 0;
      const prev = a.source === "graphic" ? "no stock result" : `weak match ${a.match}`;
      result[String(s.id)] = { ...donor, in: inPoint, note: `Reused a nearby clip (${prev})` };
      // The donor's download (if pending) also serves this scene.
      const pend = pendingDownloads.find((d) => d.cand.pageUrl === donor.url);
      if (pend) pendingDownloads.push({ sceneId: s.id, cand: pend.cand });
      reused++;
    }
    if (reused) log(`[assets] ${reused} weak scenes reuse a nearby well-matched clip`);
  }
  if (clipScores) {
    const m = stockPools.map((p) => result[String(p.scene.id)].match).filter((x): x is number => x !== undefined);
    if (m.length) log(`[assets] CLIP match: avg ${(m.reduce((a, b) => a + b, 0) / m.length).toFixed(3)}, lowest ${Math.min(...m).toFixed(3)}`);
  }

  // Download unique stock clips (3 at a time); scenes that share a clip share the file.
  const unique = [...new Map(pendingDownloads.map((d) => [d.cand.id, d.cand])).values()];
  if (unique.length) log(`[assets] downloading ${unique.length} stock clips ...`);
  const files = new Map<string, string>();
  let done = 0;
  await pool(unique, 3, async (c) => {
    try {
      files.set(c.id, await downloadCandidate(c));
    } catch (err) {
      log(`[assets] ${String(err)}`);
    }
    done++;
    if (done % 5 === 0 || done === unique.length) log(`[assets] downloaded ${done}/${unique.length}`);
  });
  for (const { sceneId, cand } of pendingDownloads) {
    const a = result[String(sceneId)];
    if (a.source !== cand.source || a.url !== cand.pageUrl) continue;
    const file = files.get(cand.id);
    if (file) a.path = file;
    else {
      const scene = scenes[sceneId];
      const card = await renderTextCard("", scene.queries[0] ?? "", cardStyle, graphicsDir);
      result[String(sceneId)] = { path: card, source: "graphic", license: GENERATED, url: "", kind: "image", width: 1920, height: 1080, note: "Stock download failed" };
    }
  }

  // Black-frame guard: some stock clips fade in from black (smoke, logos). Check the part of each
  // clip a scene will show; move the in-point past black stretches, or flag the scene for a swap.
  const ffBin = ffmpegPath();
  let shifted = 0;
  let flagged = 0;
  if (ffBin) {
    await pool(scenes, 3, async (s) => {
      const a = result[String(s.id)];
      if (a.kind !== "video" || !fs.existsSync(a.path)) return;
      const len = s.end - s.start;
      const total = a.duration ?? len + 1;
      const r = await run(ffBin, ["-hide_banner", "-nostats", "-loglevel", "info", "-i", a.path, "-an", "-vf", "scale=160:-2,blackdetect=d=0.3:pix_th=0.10", "-f", "null", "-"], { timeoutMs: 60_000 });
      const blacks = [...r.stderr.matchAll(/black_start:([\d.]+) black_end:([\d.]+)/g)].map((m) => ({ s: +m[1], e: +m[2] }));
      const hits = (from: number) => blacks.some((b) => b.e > from && b.s < from + len);
      const start = a.in ?? 0;
      if (!hits(start)) return;
      // Earliest start after a black stretch that fits the scene and shows no black.
      const options = [0, ...blacks.map((b) => b.e + 0.1)].filter((x) => x + len <= total && !hits(x));
      if (options.length) {
        a.in = Math.round(options[0] * 100) / 100;
        shifted++;
        return;
      }
      // No clean window: try the next-best options for this scene (by CLIP match) before giving up.
      const alts = (candidateFile[String(s.id)] ?? []).filter((c) => c.pageUrl !== a.url).slice(0, 3);
      for (const c of alts) {
        try {
          const file = await downloadCandidate(c);
          if (c.kind === "video") {
            const r2 = await run(ffBin, ["-hide_banner", "-nostats", "-loglevel", "info", "-i", file, "-an", "-vf", "scale=160:-2,blackdetect=d=0.3:pix_th=0.10", "-f", "null", "-"], { timeoutMs: 60_000 });
            if (/black_start/.test(r2.stderr)) continue;
          }
          result[String(s.id)] = { ...fromCandidate(s, c, c.query ?? s.queries[0]), path: file, in: c.kind === "video" ? 0.5 : 0, note: "Auto-replaced: the first pick had black frames" };
          if (c.match !== undefined) result[String(s.id)].match = c.match;
          shifted++;
          return;
        } catch {
          /* try the next option */
        }
      }
      a.note = "This clip has black frames in the part shown - swap it";
      flagged++;
    });
    if (shifted || flagged) log(`[assets] black-frame guard: ${shifted} clip(s) re-cut past black, ${flagged} flagged for a swap`);
  }

  // Manual swaps from the review page win over automatic choices.
  const overridden = applyOverrides(dir, result);
  if (overridden) log(`[assets] kept ${overridden} manual swap(s) from the review page`);

  // Thumbnails for the review page (local ffmpeg, 4 at a time).
  await pool(scenes, 4, async (s) => {
    const a = result[String(s.id)];
    const t = await makeThumb(dir, s.id, a);
    if (t) a.thumb = t;
  });

  writeLicenseLog(dir, scenes, result);
  saveCandidates(dir, candidateFile);
  writeJson(path.join(dir, "assets.json"), result);

  // M3 gate: every scene has an existing file and a license entry.
  const problems = scenes.filter((s) => {
    const a = result[String(s.id)];
    return !a || !fs.existsSync(a.path) || !a.license;
  });
  const bySource = Object.values(result).reduce<Record<string, number>>((m, a) => ((m[a.source] = (m[a.source] ?? 0) + 1), m), {});
  const notes = Object.values(result).filter((a) => a.note).length;
  const report = { scenes: scenes.length, bySource, scenesWithNotes: notes, uniqueStockClips: files.size, missing: problems.map((s) => s.id), valid: problems.length === 0 };
  writeJson(path.join(dir, "assets_report.json"), report);

  log(`[assets] sources ${JSON.stringify(bySource)}`);
  if (notes) log(`[assets] ${notes} scenes fell back to a text card (see notes in the review page)`);
  if (problems.length) {
    log(`[assets] FAILED: scenes without a usable asset: ${problems.map((s) => s.id).join(", ")}`);
    return 1;
  }
  markDone(dir, "assets", inputs);
  log(`[assets] every scene has an asset; license_log.csv has ${scenes.length} rows`);
  log(`[assets] wrote ${path.join(dir, "assets.json")}`);
  return 0;
}

interface StockPool {
  scene: Scene;
  cands: Candidate[];
  queryOf: Map<string, string>;
  /** The agent's ideal-shot sentence; CLIP compares thumbnails to it. */
  visual?: string;
}

/**
 * Downloads every candidate's thumbnail (small JPEGs) and asks the CLIP worker how well each one
 * matches its scene ("<visual phrase>. <narration>"). Returns "sceneId|candId" -> similarity, or
 * null when CLIP is unavailable (then the stock site's ranking is used).
 */
async function rankWithClip(pools: StockPool[], log: (m: string) => void): Promise<Map<string, number> | null> {
  const py = venvPythonPath();
  if (!pools.length || !py || !fs.existsSync(path.join(paths.python, "clip_score.py"))) return null;
  const unique = [...new Map(pools.flatMap((p) => p.cands).map((c) => [c.id, c])).values()];
  log(`[assets] CLIP: fetching ${unique.length} thumbnails to judge ${pools.length} scenes ...`);
  const thumbs = new Map<string, string>();
  await pool(unique, 6, async (c) => {
    const t = await downloadThumb(c);
    if (t) thumbs.set(c.id, t);
  });

  const job = {
    texts: Object.fromEntries(pools.map((p) => [String(p.scene.id), p.visual ? `${p.visual} ${p.scene.queries[0] ?? ""}` : `${p.scene.queries[0] ?? ""}. ${p.scene.text.split(/\s+/).slice(0, 25).join(" ")}`])),
    images: Object.fromEntries(thumbs),
    pairs: pools.flatMap((p) => p.cands.filter((c) => thumbs.has(c.id)).map((c) => [String(p.scene.id), c.id])),
  };
  const tmp = path.join(paths.root, "cache", "clip");
  fs.mkdirSync(tmp, { recursive: true });
  const jobFile = path.join(tmp, "job.json");
  const outFile = path.join(tmp, "scores.json");
  fs.writeFileSync(jobFile, JSON.stringify(job));
  fs.rmSync(outFile, { force: true });
  const r = await run(py, [path.join(paths.python, "clip_score.py"), "--job", jobFile, "--out", outFile, "--models-dir", path.join(paths.root, "models", "fastembed")]);
  if (r.code !== 0 || !fs.existsSync(outFile)) {
    log(`[assets] CLIP unavailable (${r.stderr.trim().split("\n").pop()?.slice(0, 160)}); using stock ranking`);
    return null;
  }
  const scores = JSON.parse(fs.readFileSync(outFile, "utf8")).scores as Record<string, number>;
  return new Map(Object.entries(scores));
}

/** Changes when files are added to or removed from the channel's media folders. */
function footageSignature(chDir: string): string {
  const list: string[] = [];
  const walk = (d: string) => {
    if (!fs.existsSync(d)) return;
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const f = path.join(d, e.name);
      if (e.isDirectory()) walk(f);
      else if (!e.name.startsWith(".")) list.push(`${f}:${fs.statSync(f).mtimeMs}`);
    }
  };
  walk(path.join(chDir, "footage"));
  walk(path.join(chDir, "presskit"));
  return String(list.sort().join("|").length) + ":" + list.length;
}

