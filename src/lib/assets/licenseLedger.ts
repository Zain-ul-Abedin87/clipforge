import fs from "node:fs";
import path from "node:path";
import type { Scene } from "../scenes.js";
import type { Asset, Assets, Candidate, Source } from "./types.js";

/**
 * Auditable licence ledger: workspace/<project>/licenses.json. One record per scene with the
 * source category, licence class, attribution duty, where the file came from and how often the
 * same clip appears in the video. license_log.csv stays as the human-readable table; this file is
 * what QA checks ("every external asset has a licence record") and what the reuse penalty reads.
 */

export const LEDGER_CATEGORIES = ["wikimedia", "archive", "unsplash", "stock", "official", "presskit", "review", "web", "own", "generated"] as const;
export type LedgerCategory = (typeof LEDGER_CATEGORIES)[number];
/** Categories that are someone else's media (everything except own clips and generated cards). */
export const EXTERNAL_CATEGORIES: LedgerCategory[] = ["wikimedia", "archive", "unsplash", "stock", "official", "presskit", "review", "web"];

export type LicenseClass = "public_domain" | "cc0" | "cc_by" | "cc_by_sa" | "stock_license" | "unsplash_license" | "editorial" | "own" | "generated" | "unknown";

export interface LicenseRecord {
  sceneId: number;
  /** Stable key of the media item (source URL, else file path). */
  assetKey: string;
  path: string;
  provider: Source | "graphic";
  category: LedgerCategory;
  license: string;
  licenseClass: LicenseClass;
  attributionRequired: boolean;
  commercialUse: boolean | "unknown";
  url: string;
  author?: string;
  /** How many scenes of this video show the same media item. */
  uses: number;
  /** First time this media item was logged for this project. */
  firstLoggedAt: string;
  loggedAt: string;
}

export interface Ledger {
  version: 1;
  generatedAt: string;
  records: LicenseRecord[];
  summary: {
    byCategory: Partial<Record<LedgerCategory, number>>;
    missing: number[];
    unknownLicense: number[];
    attributionRequired: number;
    reused: { assetKey: string; uses: number; scenes: number[] }[];
  };
}

/** Licence text -> class. Order matters: "CC BY-SA" must not read as "CC BY". */
export function classifyLicense(license: string, provider?: string): LicenseClass {
  const l = license.toLowerCase();
  if (provider === "graphic" || /generated by clipforge/.test(l)) return "generated";
  if (provider === "local" || /\bown (footage|work|clip)|own media|my clips|manual upload/.test(l)) return "own";
  if (/unknown/.test(l) || !l.trim()) return "unknown";
  if (/public domain|\bpd\b|pdm/.test(l)) return "public_domain";
  if (/cc0|cc-zero|creative commons zero/.test(l)) return "cc0";
  if (/cc[ -]?by[ -]?sa|attribution-sharealike/.test(l)) return "cc_by_sa";
  if (/cc[ -]?by(?![ -]?(nc|nd))|creative commons attribution|youtube standard cc/.test(l)) return "cc_by";
  if (/unsplash/.test(l)) return "unsplash_license";
  if (/pexels|pixabay|storyblocks|stock licen[cs]e|royalty[- ]free/.test(l)) return "stock_license";
  if (/editorial|press kit|press-kit|manufacturer|official|review use|fair use/.test(l)) return "editorial";
  return "unknown";
}

/** Provider + licence -> ledger category. */
export function ledgerCategory(provider: Source | "graphic", license = ""): LedgerCategory {
  const l = license.toLowerCase();
  switch (provider) {
    case "graphic":
      return "generated";
    case "local":
      return "own";
    case "wikimedia":
      return "wikimedia";
    case "archive":
      return "archive";
    case "unsplash":
      return "unsplash";
    case "pexels":
    case "pixabay":
    case "storyblocks":
      return "stock";
    case "presskit":
      // The official importer logs "Manufacturer product photo (..., editorial/review use)".
      return /manufacturer|official/.test(l) ? "official" : /review/.test(l) ? "review" : "presskit";
    case "youtube_cc":
    case "web_cc":
      return /review/.test(l) ? "review" : "web";
    case "youtube_exact_model":
      // Verified exact-model clips cut from YouTube reviews / walkarounds / brand channels.
      return /official|brand channel/.test(l) ? "official" : "review";
    case "web_crawl":
      return "web";
    default:
      return "web";
  }
}

const needsAttribution = (c: LicenseClass) => c === "cc_by" || c === "cc_by_sa";
const commercial = (c: LicenseClass): boolean | "unknown" =>
  c === "unknown" || c === "editorial" ? "unknown" : true;

/** A media item's identity across scenes: the source page when there is one, else the file. */
export const assetKeyOf = (a: Pick<Asset, "url" | "path">) => (a.url && a.url.trim() ? a.url.trim() : path.resolve(a.path));

/** Ledger fields for a candidate before it is downloaded (used by sources.ts / review swaps). */
export function candidateLicenseInfo(c: Pick<Candidate, "source" | "license">): { category: LedgerCategory; licenseClass: LicenseClass; attributionRequired: boolean } {
  const licenseClass = classifyLicense(c.license, c.source);
  return { category: ledgerCategory(c.source, c.license), licenseClass, attributionRequired: needsAttribution(licenseClass) };
}

/**
 * Score penalty for showing the same clip again. The first use is free; each repeat costs more, and
 * from the third use on it is steep enough that almost any fresh candidate wins.
 */
export function reusePenalty(usesSoFar: number): number {
  if (usesSoFar <= 0) return 0;
  return 0.04 * usesSoFar + (usesSoFar >= 2 ? 0.08 * (usesSoFar - 1) : 0);
}

export const ledgerFile = (dir: string) => path.join(dir, "licenses.json");

export function readLedger(dir: string): Ledger | null {
  const f = ledgerFile(dir);
  if (!fs.existsSync(f)) return null;
  try {
    return JSON.parse(fs.readFileSync(f, "utf8").replace(/^﻿/, "")) as Ledger;
  } catch {
    return null;
  }
}

/** Builds the ledger for the current assets (keeps each item's first-logged time from an older ledger). */
export function buildLedger(scenes: Pick<Scene, "id">[], assets: Assets, previous: Ledger | null = null, now = new Date().toISOString()): Ledger {
  const first = new Map((previous?.records ?? []).map((r) => [r.assetKey, r.firstLoggedAt]));
  const scenesOf = new Map<string, number[]>();
  for (const s of scenes) {
    const a = assets[String(s.id)];
    if (!a) continue;
    const k = assetKeyOf(a);
    scenesOf.set(k, [...(scenesOf.get(k) ?? []), s.id]);
  }
  const records: LicenseRecord[] = [];
  const missing: number[] = [];
  for (const s of scenes) {
    const a = assets[String(s.id)];
    if (!a || !a.license?.trim()) {
      missing.push(s.id);
      continue;
    }
    const key = assetKeyOf(a);
    const licenseClass = classifyLicense(a.license, a.source);
    records.push({
      sceneId: s.id,
      assetKey: key,
      path: a.path,
      provider: a.source,
      category: ledgerCategory(a.source, a.license),
      license: a.license,
      licenseClass,
      attributionRequired: needsAttribution(licenseClass),
      commercialUse: commercial(licenseClass),
      url: a.url ?? "",
      ...(a.author ? { author: a.author } : {}),
      uses: scenesOf.get(key)?.length ?? 1,
      firstLoggedAt: first.get(key) ?? now,
      loggedAt: now,
    });
  }
  const byCategory: Partial<Record<LedgerCategory, number>> = {};
  for (const r of records) byCategory[r.category] = (byCategory[r.category] ?? 0) + 1;
  return {
    version: 1,
    generatedAt: now,
    records,
    summary: {
      byCategory,
      missing,
      unknownLicense: records.filter((r) => r.licenseClass === "unknown" && EXTERNAL_CATEGORIES.includes(r.category)).map((r) => r.sceneId),
      attributionRequired: new Set(records.filter((r) => r.attributionRequired).map((r) => r.assetKey)).size,
      reused: [...scenesOf.entries()].filter(([k, ids]) => ids.length > 1 && records.some((r) => r.assetKey === k && r.category !== "generated")).map(([assetKey, ids]) => ({ assetKey, uses: ids.length, scenes: ids })),
    },
  };
}

export function writeLedger(dir: string, scenes: Pick<Scene, "id">[], assets: Assets): Ledger {
  const ledger = buildLedger(scenes, assets, readLedger(dir));
  fs.writeFileSync(ledgerFile(dir), JSON.stringify(ledger, null, 1));
  return ledger;
}
